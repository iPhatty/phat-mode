const list = (items: readonly string[]) => items.map((item) => `- ${item}`).join('\n');

/** mattpocock/skills triage: every AI comment during triage starts with this. */
export const AI_TRIAGE_DISCLAIMER = '> *This was generated by AI during triage.*';

export function planComment(plan: PlanReport): string {
  return `🤖 **phat-mode is working on this.**

${plan.summary}

**Plan**
${list(plan.plan)}

I'll open a draft pull request when the checks pass and the review is done.`;
}

/** Hand back to the author, in the triage skill's needs-info format. */
export function needsInfoComment(plan: PlanReport, issue: Issue, labels: { needsInfo: string; readyForAgent: string }): string {
  return `${AI_TRIAGE_DISCLAIMER}

## Triage Notes

phat-mode started on this, found a gap in the spec, and moved it back to \`${labels.needsInfo}\`.

**What we've established so far:**

${list(plan.established.length > 0 ? plan.established : [plan.summary])}

**What we still need from you (@${issue.author}):**

${list(plan.questions)}

Once these are answered, triage it to \`${labels.readyForAgent}\` again.`;
}

/** Hand back to a human, in the shape of an agent brief that says why it cannot be delegated. */
export function needsHumanComment(plan: PlanReport, labels: { readyForHuman: string }): string {
  return `${AI_TRIAGE_DISCLAIMER}

## Handed back to a human

phat-mode moved this to \`${labels.readyForHuman}\`: an agent should not do it.

**Why:** ${plan.reason || plan.summary}

**What phat-mode understood:** ${plan.summary}`;
}

export function failedComment(reason: string, labels: { readyForHuman: string; readyForAgent: string }): string {
  return `🤖 **phat-mode could not finish this issue**, so it moved it to \`${labels.readyForHuman}\`.

${reason}

Nothing was merged. Any work so far is on the \`phat-mode\` branch for this issue. To let phat-mode try again, label it \`${labels.readyForAgent}\`.`;
}

export function doneComment(prUrl: string): string {
  return `🤖 **phat-mode opened a draft pull request:** ${prUrl}`;
}

const SKILL_LINK = `[code-review @ ${MATTPOCOCK_SKILLS.short}](${MATTPOCOCK_SKILLS.url('code-review')})`;

const standardsItem = (finding: StandardsFinding) =>
  finding.kind === 'violation'
    ? `- **Violation** of ${finding.rule}${finding.where ? ` in \`${finding.where}\`` : ''}: ${finding.detail}`
    : `- *Judgement call:* ${finding.rule}${finding.where ? ` in \`${finding.where}\`` : ''}: ${finding.detail}`;

const SPEC_KIND = { missing: 'Missing or partial', unasked: 'Not asked for', wrong: 'Looks wrong', bug: 'Bug' } as const;
const specItem = (finding: SpecFinding) =>
  `- **${SPEC_KIND[finding.kind]}**${finding.where ? ` in \`${finding.where}\`` : ''}: ${finding.detail}${
    finding.specLine ? `\n  > ${finding.specLine}` : ''
  }`;

function axisSection<F>(title: string, report: AxisReport<F> | null, item: (finding: F) => string): string {
  if (report === null) return `### ${title}\n\nThe ${title} reviewer did not report.`;
  const findings = report.findings.length > 0 ? `\n\n${report.findings.map(item).join('\n')}` : '';
  return `### ${title}\n\n${report.summary.trim() || 'No findings.'}${findings}`;
}

const axisSummary = (title: string, report: AxisReport<unknown> | null) => {
  if (report === null) return `${title}: no report`;
  const count = report.findings.length;
  if (count === 0) return `${title}: no findings`;
  return `${title}: ${count} finding${count === 1 ? '' : 's'}${report.worst ? ` (worst: ${report.worst})` : ''}`;
};

/** The two axes side by side, never merged or reranked, as the skill says; then one line per axis. */
export function codeReviewSection(review: CodeReview, unresolved: boolean): string {
  const rounds = `${review.round} round${review.round === 1 ? '' : 's'}`;
  const status = unresolved
    ? '⚠️ **Findings that must be fixed are still open** after the last review round.'
    : needsFixes(review)
      ? ''
      : '✅ Nothing that must be fixed. Judgement calls, if any, are left to you.';
  return [
    `## Code review\n\nBy two reviewer agents following the ${SKILL_LINK} skill, one per axis, after ${rounds}. ${status}`.trim(),
    axisSection('Standards', review.standards, standardsItem),
    axisSection('Spec', review.spec, specItem),
    `**Summary:** ${axisSummary('Standards', review.standards)}. ${axisSummary('Spec', review.spec)}.`,
  ].join('\n\n');
}

const STATUS = { verified: '✅', failed: '❌', not_verified: '⚪' } as const;

/** One piece of evidence: an image inline, anything else as a link. Not published: its file name only. */
function evidenceLink(path: string, urls: ReadonlyMap<string, string>): string {
  const name = basename(path).replace(/^\d+-/, '');
  const url = urls.get(path);
  if (url === undefined) return `\`${name}\``;
  return IMAGE_TYPES.includes(extname(path).toLowerCase())
    ? `<img src="${url}" width="260" alt="${name}">`
    : `[${name}](${url})`;
}

const evidenceList = (paths: readonly string[], urls: ReadonlyMap<string, string>) => {
  const images = paths.filter((path) => IMAGE_TYPES.includes(extname(path).toLowerCase()));
  const others = paths.filter((path) => !images.includes(path));
  return [images.map((path) => evidenceLink(path, urls)).join(' '), others.map((path) => evidenceLink(path, urls)).join(' · ')]
    .filter((part) => part !== '')
    .join('<br>');
};

function featureItem(result: FeatureResult, urls: ReadonlyMap<string, string>, newFeatureNote: string): string {
  const subs = result.subFeatures.length > 0 ? ` (${result.subFeatures.map((id) => `\`${id}\``).join(', ')})` : '';
  const cause =
    result.status === 'failed' ? (result.preExisting ? ' Also fails on the base branch: not caused by this change.' : ' Caused by this change.') : '';
  const lines = [`- ${STATUS[result.status]} **${result.feature}**${subs}: ${indent(result.detail)}${cause}`];
  if (result.status !== 'not_verified') {
    lines.push(
      `  **Before:** ${result.before.length > 0 ? evidenceList(result.before, urls) : newFeatureNote || 'Nothing to show before.'}`,
      `  **After:** ${result.after.length > 0 ? evidenceList(result.after, urls) : 'No evidence captured.'}`,
    );
  }
  if (result.checks.length > 0) {
    lines.push(`  <details><summary>Checks (${result.checks.length})</summary>\n\n${result.checks.map((check) => `  - \`${check.replaceAll('`', "'")}\``).join('\n')}\n\n  </details>`);
  }
  return lines.join('\n');
}

/** The verifier's evidence from the real app: its own source, ahead of the implementer's claims. */
export function verificationEvidence(verification: Verification | undefined, urls: ReadonlyMap<string, string>): string[] {
  if (verification === undefined) return [];
  if (verification.kind === 'skipped') return [`- ⚪ **Not verified in the app.** ${verification.reason}`];
  const { skill, round, report, reverted, featureMapChanged, unresolved } = verification;
  const rounds = `${round} round${round === 1 ? '' : 's'}`;
  const items: string[] = [];
  if (report === null) {
    items.push(`- ⚪ **Not verified in the app:** the verifier using \`${skill}\` did not report.`);
  } else if (report.couldNotRun.trim()) {
    items.push(`- ⚪ **Verification with \`${skill}\` could not run:** ${indent(report.couldNotRun)}`);
  } else {
    const heading = unresolved
      ? `⚠️ **Verified with \`${skill}\`, after ${rounds}: failures this change caused are still open.**`
      : `**Verified in the app with \`${skill}\`**, after ${rounds}.`;
    items.push(`- ${heading} ${indent(report.summary)}`);
    for (const result of report.features) items.push(featureItem(result, urls, report.beforeNote.trim()));
    if (report.features.length === 0) items.push('- ⚪ No features of the feature map are affected by this change.');
    if (report.drift.length > 0) {
      items.push(`- ⚠️ **Feature map drift**, for \`/maintain-verification-skill\`:\n${report.drift.map((drift) => `  - ${drift}`).join('\n')}`);
    }
  }
  if (featureMapChanged.length > 0) {
    items.push(`- ℹ️ **This change edits the feature map** (${featureMapChanged.map((path) => `\`${path}\``).join(', ')}). Check the new expectations.`);
  }
  if (reverted.length > 0) {
    items.push(
      `- ⚠️ **The implementer changed the verification skill** (${reverted.map((path) => `\`${path}\``).join(', ')}). Those changes were reverted before verifying and are not in this PR.`,
    );
  }
  return items;
}

export type PullRequestDetails = {
  issue: Issue;
  spec: Spec;
  plan: PlanReport;
  done: DoneReport | undefined;
  /** The description the implementer wrote, following the pr skill; undefined if it did not. */
  pr: PrReport | undefined;
  /** What the verifier proved in the real app. */
  verification?: Verification;
  /** Published evidence: local path → URL. */
  evidenceUrls?: ReadonlyMap<string, string>;
  /** The last code review round; undefined when there was none. */
  review: CodeReview | undefined;
  /** The last review still had findings that must be fixed. */
  unresolved: boolean;
  checkCommand: string;
};

export function pullRequestTitle(issue: Issue): string {
  return `${issue.title} (#${issue.number})`;
}

/** Continuation lines of a list item, indented so multi-line Markdown stays inside it. */
const indent = (text: string) => text.trim().replaceAll('\n', '\n  ');

/** The evidence, by source: the implementer's before/after, then what phat-mode ran itself. */
export function evidence(details: Pick<PullRequestDetails, 'pr' | 'done' | 'checkCommand'>): Evidence[] {
  const { pr, done, checkCommand } = details;
  const claimed: Evidence[] =
    pr !== undefined
      ? pr.evidence.map((item) => ({ source: 'implementer', ...item }))
      : done?.testing
        ? [{ source: 'implementer', before: '', after: done.testing }]
        : [];
  return [...claimed, { source: 'phat-mode', before: '', after: `\`${checkCommand}\` passes on this code.` }];
}

function evidenceItem(item: Evidence): string {
  if (item.source === 'phat-mode') return `- ✅ **Verified by phat-mode:** ${indent(item.after)}`;
  const after = `**After:** ${indent(item.after)}`;
  return item.before.trim() ? `- **Before:** ${indent(item.before)}\n  ${after}` : `- ${after}`;
}

function mergeDanger(pr: PrReport | undefined): string {
  if (pr === undefined) return '## Merge Danger\n\nNot assessed: the implementer did not write a description.';
  return [
    '## Merge Danger',
    `**Door:** ${pr.door}`,
    pr.doorNote.trim(),
    `**Blast Radius:** ${pr.blastRadius.trim()}`,
    pr.blastNote.trim(),
  ]
    .filter((part) => part !== '')
    .join('\n\n');
}

/**
 * mattpocock/skills' `pr` template (Summary, Evidence, Merge Danger), then what phat-mode adds: the acceptance
 * criteria to tick off, the code review, and the issue link.
 */
export function pullRequestBody(details: PullRequestDetails): string {
  const { issue, spec, plan, done, pr, review, unresolved } = details;
  const sections = [
    `## Summary\n\n${pr?.summary.trim() || done?.summary || plan.summary}`,
    `## Evidence\n\n${[
      ...verificationEvidence(details.verification, details.evidenceUrls ?? new Map()),
      ...evidence(details).map(evidenceItem),
    ].join('\n')}`,
    mergeDanger(pr),
  ];
  if (spec.acceptanceCriteria.length > 0) {
    const from = spec.source === 'brief' ? 'the Agent Brief' : 'the issue';
    sections.push(
      `## Acceptance criteria\n\nFrom ${from}. For the human reviewer to tick off:\n\n${spec.acceptanceCriteria
        .map((criterion) => `- [ ] ${criterion}`)
        .join('\n')}`,
    );
  }
  if (review !== undefined) sections.push(codeReviewSection(review, unresolved));
  sections.push(
    `---\nCloses #${issue.number}\n\n🤖 Opened by phat-mode. Description written following the [pr @ ${MATTPOCOCK_SKILLS.short}](${MATTPOCOCK_SKILLS.url('pr')}) skill. This is a draft: a human must review and merge it.`,
  );
  return sections.join('\n\n');
}
