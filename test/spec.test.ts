import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { describe, test } from 'node:test';
import { testConfig } from './fakes.ts';
import { type Issue, mergeLabels, progressChange } from '../src/github.ts';
import { blockedBy, eligibility, findAgentBrief, findSpec, listUnder, parentRef } from '../src/spec.ts';

const fixture = (name: string) => readFile(join(import.meta.dirname, 'fixtures', name), 'utf8');

/** /triage's full template. */
const TEMPLATE_BRIEF = `> *This was generated by AI during triage.*

## Agent Brief

**Category:** enhancement
**Summary:** Save lesson progress

**Acceptance criteria:**
- [ ] Completing a lesson marks it completed
- [x] Progress survives an app restart,
      including after an update
- [ ] The next lesson unlocks

**Out of scope:**
- Syncing progress between devices
* Resetting progress`;

/** /to-tickets' issue template: the spec is the body. */
const TICKET_BODY = `## Parent

#3

## What to build

Completed lessons stay completed after the app restarts.

## Acceptance criteria

- [ ] Completing a lesson persists it
- [ ] Restarting the app keeps it completed

## Blocked by

- #4
- https://github.com/iPhatty/phatty-lingo/issues/5
- #6 (storage spike)`;

const issue = (fields: Partial<Issue> = {}): Issue => ({
  number: 1,
  title: 'Save progress',
  body: '',
  author: 'iPhatty',
  state: 'OPEN',
  url: '',
  labels: ['ready-for-agent'],
  comments: [],
  ...fields,
});
const comment = (author: string, body: string, createdAt = '2026-10-01T00:00:00Z') => ({ author, body, createdAt });
const config = testConfig('/tmp/unused', 'iPhatty/phatty-lingo');

describe('listUnder', () => {
  test('bold labels: checkbox and plain items, wrapped lines joined, until the next section', () => {
    assert.deepEqual(listUnder(TEMPLATE_BRIEF, 'Acceptance criteria'), [
      'Completing a lesson marks it completed',
      'Progress survives an app restart, including after an update',
      'The next lesson unlocks',
    ]);
    assert.deepEqual(listUnder(TEMPLATE_BRIEF, 'Out of scope'), ['Syncing progress between devices', 'Resetting progress']);
    assert.deepEqual(listUnder(TEMPLATE_BRIEF, 'Key interfaces'), []);
  });

  test('headings, as /to-tickets and /to-spec write them', () => {
    assert.deepEqual(listUnder(TICKET_BODY, 'Acceptance criteria'), [
      'Completing a lesson persists it',
      'Restarting the app keeps it completed',
    ]);
  });
});

describe('blockedBy', () => {
  test('reads #refs and links to issues in the same repo', () => {
    assert.deepEqual(blockedBy(TICKET_BODY, 'iPhatty/phatty-lingo'), [4, 5, 6]);
  });

  test('"None" and other repos block nothing', () => {
    assert.deepEqual(blockedBy('## Blocked by\n\n- None (can start immediately)', 'a/b'), []);
    assert.deepEqual(blockedBy('**Blocked by:** https://github.com/other/repo/issues/9', 'a/b'), []);
    assert.deepEqual(blockedBy('**Blocked by:** #7, #8', 'a/b'), [7, 8]);
  });
});

describe('parentRef', () => {
  test('the first reference under "Parent", as #N or a link into the repo', () => {
    assert.equal(parentRef(TICKET_BODY, 'iPhatty/phatty-lingo'), 3);
    assert.equal(parentRef('## Parent\n\nhttps://github.com/iPhatty/phatty-lingo/issues/1\n', 'iPhatty/phatty-lingo'), 1);
    assert.equal(parentRef('**Parent:** #12', 'a/b'), 12);
  });

  test('none without a Parent section, or when it points elsewhere', () => {
    assert.equal(parentRef('## What to build\n\nSee #4.', 'a/b'), undefined);
    assert.equal(parentRef('## Parent\n\nhttps://github.com/other/repo/issues/1', 'a/b'), undefined);
    assert.equal(parentRef('## Parent\n\nNone', 'a/b'), undefined);
  });
});

describe('findAgentBrief', () => {
  test('the /triage template: newest trusted brief, from its heading on', () => {
    const brief = findAgentBrief(
      issue({
        comments: [
          comment('iPhatty', TEMPLATE_BRIEF, '2026-10-02T00:00:00Z'),
          comment('iPhatty', '## Agent Brief\n\nold', '2026-10-01T00:00:00Z'),
          comment('iPhatty', 'Just a comment', '2026-10-03T00:00:00Z'),
        ],
      }),
      ['iPhatty'],
    );
    assert.equal(brief?.source, 'brief');
    assert.match(brief!.text, /^## Agent Brief/);
    assert.doesNotMatch(brief!.text, /generated by AI/);
    assert.equal(brief!.acceptanceCriteria.length, 3);
    assert.equal(brief!.outOfScope.length, 2);
  });

  test('real inline briefs from mattpocock/skills, "Agent brief: …"', async () => {
    for (const name of ['inline-brief-mattpocock-skills-1165.md', 'inline-brief-mattpocock-skills-1201.md']) {
      const body = await fixture(name);
      const brief = findAgentBrief(issue({ comments: [comment('mattpocock', body)] }), ['mattpocock']);
      assert.ok(brief, name);
      assert.match(brief.text, /^Agent brief: /, name);
      assert.doesNotMatch(brief.text, /generated by AI/, name);
      assert.deepEqual(brief.acceptanceCriteria, [], 'inline briefs have no criteria list');
    }
  });

  test('also bold inline briefs', () => {
    const brief = findAgentBrief(issue({ comments: [comment('iPhatty', '**Agent brief:** add a hello file.')] }), ['iPhatty']);
    assert.equal(brief?.text, '**Agent brief:** add a hello file.');
  });

  test('not a brief: a mention of "agent brief" mid-sentence', () => {
    assert.equal(
      findAgentBrief(issue({ comments: [comment('iPhatty', 'I will write an agent brief: later.')] }), ['iPhatty']),
      undefined,
    );
  });

  test('ignores briefs from anyone else', () => {
    assert.equal(findAgentBrief(issue({ comments: [comment('stranger', TEMPLATE_BRIEF)] }), ['iPhatty']), undefined);
  });
});

describe('findSpec', () => {
  test('a /to-tickets issue: the body is the spec, with criteria and blockers', () => {
    const spec = findSpec(issue({ body: TICKET_BODY }), ['iPhatty'], 'iPhatty/phatty-lingo');
    assert.equal(spec?.source, 'issue');
    assert.equal(spec?.acceptanceCriteria.length, 2);
    assert.deepEqual(spec?.blockedBy, [4, 5, 6]);
  });

  test('a brief wins over the body, but the body’s blockers still count', () => {
    const spec = findSpec(
      issue({ body: TICKET_BODY, comments: [comment('iPhatty', TEMPLATE_BRIEF)] }),
      ['iPhatty'],
      'iPhatty/phatty-lingo',
    );
    assert.equal(spec?.source, 'brief');
    assert.equal(spec?.acceptanceCriteria.length, 3);
    assert.deepEqual(spec?.blockedBy, [4, 5, 6]);
  });
});

describe('eligibility', () => {
  test('ready-for-agent with a trusted brief: yes, even if someone else opened the issue', () => {
    const result = eligibility(issue({ author: 'stranger', comments: [comment('iPhatty', TEMPLATE_BRIEF)] }), config);
    assert.equal(result.ok && result.spec.source, 'brief');
  });

  test('ready-for-agent, no brief, opened by a trusted author: yes, the issue is the spec', () => {
    const result = eligibility(issue(), config);
    assert.equal(result.ok && result.spec.source, 'issue');
  });

  test('not ready-for-agent, closed, or untrusted without a trusted brief: no', () => {
    const notReady = eligibility(issue({ labels: ['needs-triage'] }), config);
    assert.match(!notReady.ok ? notReady.reason : '', /not labelled `ready-for-agent`/);
    assert.equal(eligibility(issue({ state: 'CLOSED' }), config).ok, false);
    assert.equal(eligibility(issue({ author: 'stranger', comments: [comment('stranger', TEMPLATE_BRIEF)] }), config).ok, false);
  });

  test('follows the configured label names', () => {
    const custom = { ...config, labels: { ...config.labels, readyForAgent: 'agent:ready' } };
    assert.equal(eligibility(issue({ labels: ['agent:ready'] }), custom).ok, true);
    assert.equal(eligibility(issue(), custom).ok, false);
  });
});

describe('labels', () => {
  test('progressChange shows one progress label and removes the others', () => {
    assert.deepEqual(progressChange('working'), { add: ['phat-mode:working'], remove: ['phat-mode:done', 'phat-mode:failed'] });
    assert.deepEqual(progressChange(null), { add: [], remove: ['phat-mode:working', 'phat-mode:done', 'phat-mode:failed'] });
  });

  test('mergeLabels: adding wins over removing', () => {
    assert.deepEqual(mergeLabels({ add: ['a'], remove: ['b', 'c'] }, { add: ['c'], remove: ['a', 'd'] }), {
      add: ['a', 'c'],
      remove: ['b', 'd'],
    });
  });
});
